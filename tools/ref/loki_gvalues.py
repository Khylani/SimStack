#!/usr/bin/env python3
"""G-values (per 100 eV) of the SimStack air source from a LoKI-B++ sweep.

Input: a LoKI-B++ output folder (reducedField_*/rateCoefficients.txt and
lookUpTablePower.txt) for dry air, and the LXCat files it used (thresholds).
Output: src/sim/kinetics/air_source_table.h

  G_j = 100 * k_j * x_target / P_field      (P_field: electron power per gas density, eV m^3/s)

Channel mapping (neutral source of air_mech.cpp):
  O2 dissociation  O2 -> O + O, O2 -> O + O(1D) (8.4 eV), O2(9.97 eV) and O2(14.7 eV)
                   (predissociative, counted with O(1D)), dissociative attachment
                   O2 -> O- + O (O- detaches: one dissociation), and the bound N2
                   singlets a', a, w, a'' (quenched by O2 into N2 + O + O, Kossyi 1992)
  N2(A)            all N2 triplets A (v=0-4, 5-9, 10+), B, W, B', C, E: radiative
                   cascade and quenching feed N2(A) or dissociate O2 like it
  N2 dissociation  N2(sing-sup) (> 13 eV singlets, predissociating to N + N(2D))
  heat             ionization (N2+ / O2+ cluster to O4+ in air and recombine to 2 O2),
                   O2(a, b) and Herzberg states, rotations, elastic; N2 vibration is
                   reported separately (eta_vib) for the vibrational energy budget
"""
import glob, os, re, sys

def lxcat_thresholds(path):
    """{description: threshold eV} from the COMMENT '[...]' lines of an IST-Lisbon LXCat file."""
    out = {}
    lines = open(path, errors="replace").read().splitlines()
    i = 0
    while i < len(lines):
        if lines[i].strip() in ("EXCITATION", "IONIZATION", "ATTACHMENT"):
            kind = lines[i].strip()
            thr = 0.0
            if kind != "ATTACHMENT":
                try: thr = float(lines[i + 2].split()[0])
                except ValueError: thr = 0.0
            j = i + 1
            while j < len(lines) and not lines[j].startswith("-----"):
                m = re.match(r"COMMENT:\s*\[(.*?)\]", lines[j])
                if m: out[m.group(1).strip()] = thr
                j += 1
            i = j
        i += 1
    return out

def main(run_dir, lxcat_files, out_h, x_n2=0.79, x_o2=0.21):
    thr = {}
    for f in lxcat_files: thr.update(lxcat_thresholds(f))
    power = {}
    for line in open(os.path.join(run_dir, "lookUpTablePower.txt")):
        t = line.split()
        if t and t[0][0] in "+-0123456789":
            power[round(float(t[0]), 6)] = float(t[1])
    rows = []
    ev_rows = []
    for d in sorted(glob.glob(os.path.join(run_dir, "reducedField_*")), key=lambda p: float(p.rsplit("_", 1)[1])):
        en = float(d.rsplit("_", 1)[1])
        P = power[round(en, 6)]
        g = dict(o2diss=0.0, o1d=0.0, n2a=0.0, n2diss=0.0, vib=0.0)
        ev = {}   # G(N2 v=0 -> v) per 100 eV, for the state-to-state reference (tools/ref/n2vib)
        for line in open(os.path.join(d, "rateCoefficients.txt")).read().splitlines()[1:]:
            t = line.split(None, 2)
            if len(t) < 3 or t[0][0] not in "+-0123456789": continue   # section separators / headers
            k, desc = float(t[0]), t[2].strip()
            x = x_n2 if "N2(" in desc.split("->")[0].split("<->")[0] else x_o2
            G = 100.0 * k * x / P
            if "O(3P) + O(3P)" in desc or "O(-,gnd)" in desc: g["o2diss"] += G
            elif "O(3P) + O(1D)" in desc or "O2(9.97eV)" in desc or "O2(14.7eV)" in desc:
                g["o2diss"] += G; g["o1d"] += G
            elif re.search(r"N2\((A3|B3|W3|C3|E3)", desc): g["n2a"] += G
            elif re.search(r"N2\((a1Su-|a1Pg|w1Du|a1Sg\+)\)", desc): g["o2diss"] += G
            elif "N2(sing-sup)" in desc: g["n2diss"] += G
            elif "Vibrational" in desc and "N2(X" in desc:
                e = thr.get(desc.replace(", Vibrational", "").strip(), None)
                m = re.search(r"v=(\d+)\)", desc.split("<->")[-1])
                ev_e = e if e else 0.29 * int(m.group(1))
                g["vib"] += k * x_n2 * ev_e / P   # fraction of the power
                if m and "N2(X,v=0)" in desc.split("<->")[0]: ev[int(m.group(1))] = 100.0 * k * x_n2 / P
        rows.append((en, g["o2diss"], g["o1d"] / g["o2diss"] if g["o2diss"] > 0 else 0.0, g["n2a"], g["n2diss"], g["vib"]))
        ev_rows.append((en, [ev.get(v, 0.0) for v in range(1, 11)]))
    with open(out_h, "w") as f:
        f.write("// Generated by tools/ref/loki_gvalues.py from a LoKI-B++ sweep (IST-Lisbon N2 / O2\n")
        f.write("// cross sections, dry air 79/21, 1 atm, 330 K, steady-state two-term Boltzmann).\n")
        f.write("// Per 100 eV of electron power at each reduced field. Do not edit by hand.\n")
        f.write("// columns: E/N (Td), O2 dissociations, O(1D) share, N2(A) (all triplets), N2 -> N + N(2D), N2 vibration share\n")
        f.write("#define AIR_SOURCE_TABLE_ROWS %d\n" % len(rows))
        f.write("global const f64 air_source_table[AIR_SOURCE_TABLE_ROWS][6] = {\n")
        for r in rows: f.write("    { %6.1f, %.5f, %.5f, %.5f, %.5f, %.5f },\n" % r)
        f.write("};\n")
    ev_csv = os.path.join(os.path.dirname(os.path.abspath(__file__)), "n2vib", "ev_gvalues.csv")
    os.makedirs(os.path.dirname(ev_csv), exist_ok=True)
    with open(ev_csv, "w") as f:
        f.write("# G(N2 X v=0 -> v) per 100 eV of electron power, dry air 79/21, LoKI-B++ (IST-Lisbon)\n")
        f.write("EN_Td," + ",".join("v%d" % v for v in range(1, 11)) + "\n")
        for en, g in ev_rows: f.write("%.1f," % en + ",".join("%.6g" % x for x in g) + "\n")
    for r in rows:
        if r[0] in (100.0, 150.0, 180.0, 200.0, 250.0, 300.0, 400.0):
            print("E/N %5.0f Td: G(O2 diss) %.2f (O(1D) %.0f %%), G(N2(A)) %.2f, G(N2 diss) %.3f, vibration %.0f %%"
                  % (r[0], r[1], 100 * r[2], r[3], r[4], 100 * r[5]))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:-1], sys.argv[-1])
